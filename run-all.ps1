# ?????????????????????????????????????????????????????????????????????????????
# run-all.ps1  -  Launch the AFP stack locally
#   1. Node.js API   (railway-backend, port 3000)
#   2. .NET frontend (Razor Pages, https://localhost:7207)
#
# Usage:  right-click ? Run with PowerShell,  or  .\run-all.ps1
# ?????????????????????????????????????????????????????????????????????????????

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path

Write-Host "Starting AFP stack from $root" -ForegroundColor Cyan

# 1) Node.js API ?????????????????????????????????????????????????????????????
Write-Host "? Starting Node.js API (port 3000)..." -ForegroundColor Yellow
Start-Process powershell -ArgumentList @(
    "-NoExit",
    "-Command",
    "cd '$root\railway-backend'; Write-Host 'AFP API' -ForegroundColor Green; npm start"
)

# Give the API a moment to bind before starting the frontend
Start-Sleep -Seconds 3

# 2) .NET Razor Pages frontend ???????????????????????????????????????????????
Write-Host "? Starting .NET frontend (https://localhost:7207)..." -ForegroundColor Yellow
Start-Process powershell -ArgumentList @(
    "-NoExit",
    "-Command",
    "cd '$root'; Write-Host 'AFP Frontend' -ForegroundColor Green; dotnet run --launch-profile https"
)

Write-Host ""
Write-Host "Both services launching in separate windows." -ForegroundColor Cyan
Write-Host "  API      : http://localhost:3000/health"
Write-Host "  Frontend : https://localhost:7207"
Write-Host ""
Write-Host "Seeded admin login  ?  mobile: 9999999999   password: Admin@123"
